#!/usr/bin/env node
// Projects the corpus embeddings (src/data/ai-vectors.json) to 2D for the
// embedding explorer on /ai and writes public/ai/projection.json: points and
// labels only, never chunk text or vectors. Only /ai loads the file.
//
// The projection is plain PCA in pure JS, deterministic run to run: the vectors
// are centred, the top two eigenvectors of the Gram matrix come from power
// iteration with a fixed start and deflation, and each axis's sign is pinned so
// its largest coordinate is positive. Both axes share one scale, so distances
// on the map keep their proportions.
//
// Only vectors whose hash matches the current corpus chunk are used (a stale
// vector would place a chunk by text it no longer has). With no vectors it
// writes an empty projection, which the explorer shows as 'Embeddings not
// generated yet'. It needs no key.
//
//   node --env-file-if-exists=.env scripts/ai/project-embeddings.mjs

import path from 'node:path';
import { decodeVec } from '../../src/lib/ai/retrieval.ts';
import { loadCorpus, readJson, ROOT, VECTORS_PATH, writeJson } from './lib.mjs';

// --vectors and --out exist for tests; the defaults are the committed files.
const argOf = (flag) => {
  const i = process.argv.indexOf(flag);
  return i > 0 && process.argv[i + 1] ? path.resolve(process.argv[i + 1]) : null;
};
const PROJECTION_PATH = argOf('--out') ?? path.join(ROOT, 'public/ai/projection.json');
const vectorsPath = argOf('--vectors') ?? VECTORS_PATH;
const rel = path.relative(ROOT, PROJECTION_PATH).replaceAll('\\', '/');
const NOTE = 'Generated by scripts/ai/project-embeddings.mjs from src/data/ai-vectors.json. Do not edit.';

const { chunks } = loadCorpus();
const file = readJson(vectorsPath, { model: null, entries: {} });

const rows = [];
if (file.model) {
  for (const c of chunks) {
    const e = file.entries?.[c.id];
    if (e && e.hash === c.hash) rows.push({ chunk: c, vec: decodeVec(e) });
  }
}

if (rows.length < 3) {
  writeJson(PROJECTION_PATH, { version: 1, note: NOTE, model: file.model ?? null, count: 0, explained: [], points: [] });
  console.log(`Wrote ${rel}: empty (${rows.length ? `only ${rows.length} fresh vectors` : 'no vectors'}; run npm run ai:embed with a key first).`);
  process.exit(0);
}

const n = rows.length;
const d = rows[0].vec.length;

// Centre.
const mean = new Float64Array(d);
for (const { vec } of rows) for (let j = 0; j < d; j++) mean[j] += vec[j] / n;
const X = rows.map(({ vec }) => Float64Array.from(vec, (v, j) => v - mean[j]));

// Gram matrix G = X Xᵀ (n×n is far smaller than d×d here).
const G = Array.from({ length: n }, () => new Float64Array(n));
for (let i = 0; i < n; i++) {
  for (let k = i; k < n; k++) {
    let s = 0;
    const a = X[i];
    const b = X[k];
    for (let j = 0; j < d; j++) s += a[j] * b[j];
    G[i][k] = s;
    G[k][i] = s;
  }
}
let trace = 0;
for (let i = 0; i < n; i++) trace += G[i][i];

function multiply(M, v) {
  const out = new Float64Array(n);
  for (let i = 0; i < n; i++) {
    let s = 0;
    const row = M[i];
    for (let k = 0; k < n; k++) s += row[k] * v[k];
    out[i] = s;
  }
  return out;
}

function normalise(v) {
  let s = 0;
  for (const x of v) s += x * x;
  const len = Math.sqrt(s) || 1;
  return v.map((x) => x / len);
}

/** The dominant eigenpair by power iteration from a fixed, non-degenerate start. */
function topEigen(M) {
  let v = normalise(Float64Array.from({ length: n }, (_, i) => 1 + ((i * 7919) % 97) / 97));
  let lambda = 0;
  for (let iter = 0; iter < 1000; iter++) {
    const w = multiply(M, v);
    let dot = 0;
    for (let i = 0; i < n; i++) dot += w[i] * v[i];
    const next = normalise(w);
    let diff = 0;
    for (let i = 0; i < n; i++) diff = Math.max(diff, Math.abs(next[i] - v[i]));
    v = next;
    lambda = dot;
    if (diff < 1e-12) break;
  }
  return { lambda: Math.max(lambda, 0), v };
}

const first = topEigen(G);
const deflated = G.map((row, i) => row.map((x, k) => x - first.lambda * first.v[i] * first.v[k]));
const second = topEigen(deflated);

/** Principal-component scores: u·sqrt(λ), with the sign pinned for stable output. */
function scores({ lambda, v }) {
  const s = Math.sqrt(lambda);
  let pivot = 0;
  for (let i = 1; i < n; i++) if (Math.abs(v[i]) > Math.abs(v[pivot])) pivot = i;
  const sign = v[pivot] < 0 ? -1 : 1;
  return Array.from(v, (x) => sign * x * s);
}

const xs = scores(first);
const ys = scores(second);
const scale = Math.max(...xs.map(Math.abs), ...ys.map(Math.abs)) || 1;
const round = (x) => Math.round((x / scale) * 1e4) / 1e4;

const points = rows
  .map(({ chunk }, i) => ({ id: chunk.id, label: chunk.label, cls: chunk.cls, x: round(xs[i]), y: round(ys[i]) }))
  .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));

const explained = trace > 0 ? [first.lambda / trace, second.lambda / trace].map((r) => Math.round(r * 1e4) / 1e4) : [];
writeJson(PROJECTION_PATH, { version: 1, note: NOTE, model: file.model, count: points.length, explained, points });
console.log(
  `Wrote ${rel}: ${points.length} points from ${file.model}` +
    (explained.length ? `, PC1 ${(explained[0] * 100).toFixed(1)}% + PC2 ${(explained[1] * 100).toFixed(1)}% of variance.` : '.'),
);
